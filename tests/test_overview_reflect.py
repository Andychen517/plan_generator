def run_lenses(xuqiu, xianzhuang, tag):
    print(f"\n########## {tag} ##########")
    hints = og.precheck(xuqiu, xianzhuang)
    ic, skeleton = og.lens_consistency(xuqiu, xianzhuang, REQ)
    print(f"  镜头1 一致性: {len(ic)} 条")
    if_ = og.lens_fidelity(xuqiu, xianzhuang, FAKE_SOURCE)
    print(f"  镜头2 忠实性: {len(if_)} 条")
    is_ = og.lens_style(xuqiu, xianzhuang, hints)
    print(f"  镜头3 表达: {len(is_)} 条")
    issues = ic + if_ + is_
    for i, it in enumerate(issues, 1):
        print(f"  问题{i} [{it.get('lens')}{it.get('check', '')}|{it.get('section')}] "
              f"{it.get('problem')} | 原文: {it.get('quote')}")
    return issues, skeleton


